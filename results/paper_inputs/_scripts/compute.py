"""Task 1: GPU-hours per run directory and model, from logs/lanes.log START/END (wall time incl. model load).
pilot_rep2 has no START line (scripts/lane.sh runs it right after the same model's pilot), so its start = that END."""
import gzip, json, re, subprocess
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
lines = (ROOT / "logs/lanes.log").read_text().splitlines()
ev = {}
for i, l in enumerate(lines, 1):
    m = re.match(r"\[(\S+)\] (START|END) (\S+) (\S+)", l)
    if m:
        ts, kind, model, run = m.groups()
        ev.setdefault((run, model), {})[kind] = (ts, i)
DIRS = ["main", "main_run2", "main_run3", "ext/run1", "ext/run2", "ext/run3", "res896", "res_gemma_nopas", "pilot", "pilot_rep2", "ext/pilot"]
GROUP = {"main": "primary", "main_run2": "replication", "main_run3": "replication", "ext/run1": "extension", "ext/run2": "extension",
         "ext/run3": "extension", "ext/pilot": "pilot", "res896": "resolution", "res_gemma_nopas": "resolution", "pilot": "pilot", "pilot_rep2": "pilot"}
rows = []
for d in DIRS:
    for meta in sorted((ROOT / "results/raw" / d).glob("*.jsonl.meta.json")):
        m = json.loads(meta.read_text())
        mid, tp = m["model_id"], m["tensor_parallel_size"]
        jl = meta.with_name(meta.name.replace(".meta.json", ""))
        p = jl if jl.exists() else Path(str(jl) + ".gz")
        n = sum(1 for _ in (gzip.open(p, "rt") if p.suffix == ".gz" else open(p)))
        e = ev.get((d, mid), {})
        src = []
        if "START" in e:
            st = e["START"][0]; src.append(f"logs/lanes.log:{e['START'][1]}")
        elif d == "pilot_rep2" and ("pilot", mid) in ev:
            st = ev[("pilot", mid)]["END"][0]; src.append(f"start = pilot END, logs/lanes.log:{ev[('pilot', mid)]['END'][1]} (scripts/lane.sh runs rep2 right after pilot)")
        else:
            st = None
        en = e.get("END", (None,))[0]
        if "END" in e:
            src.append(f"logs/lanes.log:{e['END'][1]}")
        wall = (pd.Timestamp(en) - pd.Timestamp(st)).total_seconds() / 3600 if st and en else float("nan")
        rows.append(dict(group=GROUP[d], run=d, model=mid, n_records=n, start_utc=st, end_utc=en, wall_h=round(wall, 3), n_gpus=tp,
                         gpu_h=round(wall * tp, 3), source="; ".join(src) or "NOT FOUND"))
df = pd.DataFrame(rows)
gpu = subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total,driver_version", "--format=csv"], capture_output=True, text=True).stdout
L = ["# Compute: hardware and GPU-hours", "",
     "## Hardware", "", "Command: `nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv`", "", "```", gpu.strip(), "```", "",
     "The server has 4 of these GPUs; runs used GPU 0 and 1 only (TP=2 jobs use both).", "",
     "## GPU-hours", "",
     "- wall_h = END - START in `logs/lanes.log` (written by scripts/lane.sh, lane4.sh, res.sh, t17.sh): one fresh process per model-run, so it **includes model loading and vLLM warm-up**.",
     "- n_gpus = `tensor_parallel_size` in the run's `*.jsonl.meta.json`; gpu_h = wall_h × n_gpus.",
     "- Two jobs often ran at the same time on different GPUs, so the sum of GPU-hours is not elapsed time.",
     "- Not included: `results/raw/pilot_smoke` (smoke test, 2 items per type) and failed launch attempts not in lanes.log.", "",
     df.drop(columns="group").to_markdown(index=False), "", "## Totals per group", "",
     df.groupby("group", sort=False).agg(n_model_runs=("model", "size"), wall_h=("wall_h", "sum"), gpu_h=("gpu_h", "sum")).round(3).reset_index().to_markdown(index=False),
     "", f"**Grand total: {df.gpu_h.sum():.2f} GPU-hours** over {len(df)} model-runs (generated by `results/paper_inputs/_scripts/compute.py`).", ""]
(ROOT / "results/paper_inputs/compute.md").write_text("\n".join(L))
print(df.groupby("group", sort=False).gpu_h.sum().round(2).to_dict(), df.gpu_h.sum().round(2), df.source.str.contains("NOT FOUND").sum())
